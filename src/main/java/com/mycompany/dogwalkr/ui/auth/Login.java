    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        try {
            String email = inputEmail.getText().trim();
            String password = new String( inputPassword.getPassword());
            
            if (email.isEmpty() || password.isEmpty()){
                JOptionPane.showMessageDialog(this,"Email and password are mandatory");
                return;
            }
            User user = UserService.login(email,password);
            if(user == null){
                JOptionPane.showMessageDialog(this,"Invalid email or password, please enter valid one",
                        "Failed to login",JOptionPane.ERROR_MESSAGE);
                return;
            }
            if(user.status.equals("Pending")){
                JOptionPane.showMessageDialog(this, "Account is not activated by admin yet. status is pending. please wait for a while");
            }
            if (user.status.equals("Rejected")){
                JOptionPane.showMessageDialog(this, "Sorry, you are not a valid user and Rejected by Admin");
            }
            
            Session.currentUser = user;
            
            
            
            if (user.role.equals("ADMIN") && user.status.equals("Approved")){
                new AdminPanel().setVisible(true);
                this.dispose();
            }
            else if (user.role.equals("OWNER")&& user.status.equals("Approved")){
                  new OwnerPanel().setVisible(true);
                  this.dispose();
            }
            else if (user.role.equals("WALKER")&& user.status.equals("Approved")) {
                new WalkerPanel().setVisible(true);
                this.dispose();
            }
            
        } catch (SQLException ex) {
            System.getLogger(Login.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

