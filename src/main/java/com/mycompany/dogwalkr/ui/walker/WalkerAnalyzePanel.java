    // walks 
    
    private void loadWalks(){
        WalkService.completeFinishedWalks();
        tmodel.setRowCount(0);
        if(Session.currentUser == null){
            return ;
          }
        currentWalks  = WalkService.getWalksByWalker((int) Session.currentUser.id);
      
        DateTimeFormatter f = DateTimeFormatter.ofPattern("dd MMM yyyy, hh:mm a");
        
        for (WalkHistory w : currentWalks){
            String ist =w.walkTime.atZoneSameInstant(ZoneId.of("Asia/Kolkata")).format(f);
            tmodel.addRow(new Object[]{
                w.dogName,ist,w.durationMinutes +" Mins" ,w.status , "\u20b9 "+w.walkerPay
            });
        }
        updateStatus(currentWalks);
        
    }
    
    
    // fetch values for total walks, durations and requestes
    
    private void updateStatus(List<WalkHistory> walks){
       
        int accepted = 0;
        int completed = 0;
        int minutes = 0;
        int earned = 0;
        
        for (WalkHistory w: walks ){
            
           if("Accepted".equalsIgnoreCase(w.status)){
                accepted++;
            }
            else if("Completed".equalsIgnoreCase(w.status)){
                  completed++;
                  minutes +=w.durationMinutes;
                  earned += w.walkerPay;
        }
        }
        
        
        lblAccepted.setText(String.valueOf(accepted));
        lblCompleted.setText(String.valueOf(completed));
        lblTotalMinutes.setText(String.valueOf(minutes));
        lblTotalEarned.setText("\u20b9 "+earned);
        
        
        
    }
    
