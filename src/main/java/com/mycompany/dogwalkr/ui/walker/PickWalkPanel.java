    private void setupTable(){
        DefaultTableModel tmodel = new DefaultTableModel(
                            new Object[]{"Dog","Date & Time (IST)","Duration","You Earn","Notes"},0){
                              @Override
                            public boolean isCellEditable(int row,int column){
                                return false;
                            }
                            }; 
        
        tblAvailable.setModel(tmodel);
        tblAvailable.setRowHeight(28);
        tblAvailable.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        
    }
    
    private void loadAvailable(){
        int selectedId = -1;
        int row = tblAvailable.getSelectedRow();
        if(row>=0 && row<currentWalks.size()){
            selectedId = currentWalks.get(row).id;
        }
        
        currentWalks = WalkService.getAvailableWalks();
        
        DefaultTableModel tmodel = (DefaultTableModel) tblAvailable.getModel();
        tmodel.setRowCount(0);
        
        for(WalkHistory h : currentWalks){
            tmodel.addRow(new Object[]{
                h.dogName,
                h.walkTime.atZoneSameInstant(APP_ZONE).format(FMT),
                h.durationMinutes + " min" ,
                " \u20b9 "+h.walkerPay,
                h.notes
                
            });
        }
        
        lblCount.setText(String.valueOf(currentWalks.size()));
        
        if(selectedId !=-1){
            for(int i=0; i<currentWalks.size();i++){
                if(currentWalks.get(i).id == selectedId){
                    tblAvailable.setRowSelectionInterval(i,i);
                    break;
                }
            }
        }
        
    }
    
