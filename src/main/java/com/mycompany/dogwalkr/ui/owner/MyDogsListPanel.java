    public void loadDogs(int ownerId){
        this.ownerId = ownerId;
        dogs = DogService.getDogsByOwner(ownerId);
        
        DefaultTableModel tmodel = (DefaultTableModel) tblDogs.getModel();
        tmodel.setRowCount(0);
        
        for (Dog d : dogs){
            tmodel.addRow(new Object[]{d.name,d.breed,d.age,d.notes});
        }
        lblPhoto.setIcon(null);
        lblPhoto.setText(dogs.isEmpty()? "No dogs added yet": "Select a dog");
        
     
    }
    
    private void showPhoto(int row){
        if(row <0 || row>=dogs.size()){
            return;
        }
        Dog d = dogs.get(row);
        if(d.photo==null || d.photo.length==0){
            lblPhoto.setIcon(null);
            lblPhoto.setText("No image");
            return;
        }
        int w = Math.max(lblPhoto.getWidth()-10, 100);
        int h = Math.max(lblPhoto.getHeight()-10,100);
        Image img =new ImageIcon(d.photo).getImage().getScaledInstance(w,h,Image.SCALE_SMOOTH);
        lblPhoto.setText("");
        lblPhoto.setIcon(new ImageIcon(img));
}

