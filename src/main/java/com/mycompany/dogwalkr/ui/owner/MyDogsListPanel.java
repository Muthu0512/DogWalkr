    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = tblDogs.getSelectedRow();
        if(row<0){
            JOptionPane.showMessageDialog(this, "select dog which is you want to delete");
            return;
        }
        Dog d =dogs.get(row);
        int choice = JOptionPane.showConfirmDialog(this, " Are you sure want to Delete "+d.name +"?. This can't be undone" ,
               "Delete dog ", JOptionPane.YES_NO_OPTION);
        if(choice != JOptionPane.YES_OPTION){
            return ;
        }
        if(DogService.deleteDog(d.id, ownerId)){
            loadDogs(ownerId);
        }else{
            JOptionPane.showMessageDialog(this, "Unable to delete. please try after sometimes");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

