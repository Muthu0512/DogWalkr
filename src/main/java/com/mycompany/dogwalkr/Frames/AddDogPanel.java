    private void btnAddPhotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddPhotoActionPerformed
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Choose a Dog photo");
        chooser.setAcceptAllFileFilterUsed(false);
        chooser.setFileFilter(new FileNameExtensionFilter("Images (JPG,PNG)", "jpg", "jpeg", "png"));

        if (chooser.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) {
            return;
        }
        File file = chooser.getSelectedFile();
        String fileName = file.getName().toLowerCase();

        if (!(fileName.endsWith(".jpg") || fileName.endsWith(".jpeg") || fileName.endsWith(".png"))) {
            JOptionPane.showMessageDialog(this, "Please choose a jpg or png format only");
            return;
        }
        if (file.length() > 2 * 1024 * 1024) {
            JOptionPane.showMessageDialog(this, "Image size is too big, please pick less than 2MB.");
            return;
        }
        try {
            BufferedImage img = ImageIO.read(file);
            if (img == null) {
                JOptionPane.showMessageDialog(this, "This file is not a valid image");
                return;
            }
            photoBytes = Files.readAllBytes(file.toPath());
            Image scaled = img.getScaledInstance(80, 80, Image.SCALE_SMOOTH);
            btnAddPhoto.setIcon(new ImageIcon(scaled));
            btnAddPhoto.setText("");
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "could not read the image" + e.getMessage());
        }
    }//GEN-LAST:event_btnAddPhotoActionPerformed

