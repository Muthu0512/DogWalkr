    private void btnAddDogActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddDogActionPerformed
        if (Session.currentUser == null) {
            JOptionPane.showMessageDialog(this, "Please login first");
            return;
            
        } 
        String name =btnAddName.getText().trim();
        String breed = btnAddBreed.getText().trim();

        if (name.isEmpty() || breed.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Dog name and breed are required");
            return;
                }
        Dog dog = new Dog();
        dog.ownerId = (int) Session.currentUser.id;
        dog.name = name;
        dog.breed = breed;
        dog.age = (int) btnAddAge.getValue();
        dog.notes = btnAddNotes.getText().trim();
        dog.photo = photoBytes;
        boolean saved = DogService.addDog(dog);
        if (saved) {
            JOptionPane.showMessageDialog(this, "Dog details are saved successfully");
            btnAddName.setText("");
            btnAddBreed.setText("");
            btnAddAge.setValue(0);
            btnAddNotes.setText("");
            photoBytes = null;
            btnAddPhoto.setIcon(null);
            btnAddPhoto.setText("Choose Photo");
        } else {
            JOptionPane.showMessageDialog(this, "Could not save the dog details, please try again");
        }


    }//GEN-LAST:event_btnAddDogActionPerformed

