    private void btnSignupActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignupActionPerformed
           String username= inputUsername.getText().trim();
        String email = inputEmail.getText().trim();
        String mobile = inputMobile.getText().trim();
        String password = new String (inputPassword.getPassword());
        String confirmPassword = new String  (inputConfirmPassword.getPassword());
        
        String role = inputRole.getSelectedItem().toString().toUpperCase();
        
        if(username.isEmpty() || email.isEmpty() || mobile.isEmpty() || password.isEmpty()){
            JOptionPane.showMessageDialog(this, "All fields are mandatory , please fill all");
            return ;
        }
        if(!email.contains("@") || !email.contains(".")){
            JOptionPane.showMessageDialog(this, "Wrong email format, please Enter a valid email");
            return ;
        }
        if(!mobile.matches("\\d{10}")){
            JOptionPane.showMessageDialog(this,"Mobile number must be 10 digits");
            return ;
        }
        if(password.length()<6){
            JOptionPane.showMessageDialog(this, "Password must be atleast 6 characters");
            return ;
        }
        if(!password.equals(confirmPassword)){
            JOptionPane.showMessageDialog(this,"Password and confirm password should be same");
            return ;
        }
        String result = UserService.register(username,email,mobile,role,password);
        
        if(result.equals("OK")){
            JOptionPane.showMessageDialog(this, "Registered successfully, please wait until Admin approval");
            new Login().setVisible(true);
            this.dispose();
        }
        else{
            JOptionPane.showMessageDialog(this, result,"Failed to Register user",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSignupActionPerformed

