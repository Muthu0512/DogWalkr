    private void loadDogs(){
        cmbSelectDog.removeAllItems();
        if(Session.currentUser == null){
            return;
        }
        List<Dog> dogs =DogService.getDogsByOwner((int)Session.currentUser.id);
        for (Dog d: dogs){
            cmbSelectDog.addItem(d);
        }
    }
    
