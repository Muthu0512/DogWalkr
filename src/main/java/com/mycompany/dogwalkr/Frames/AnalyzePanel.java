    private void btnCancelWalkMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnCancelWalkMouseClicked
       int row =tblWalks.getSelectedRow();
       if(row==-1){
           JOptionPane.showMessageDialog(this,"Plese select a walk to modify it");
          return;
       }
       int index =tblWalks.convertRowIndexToModel(row);
       WalkHistory w =currentWalks.get(index);
       if(!"Requested" .equals(w.status)){
           JOptionPane.showMessageDialog(this, "Only walks with Requested are eligible to cancel");
           return;
       }
       int choice =JOptionPane.showConfirmDialog(this, "Cancel the walk for " +w.dogName + " ? " , " Cancel Walk ", JOptionPane.YES_NO_OPTION);
       
       if(choice !=JOptionPane.YES_OPTION){
           return;
       }
       
       boolean ok =WalkService.cancelWalk(w.id,(int) Session.currentUser.id );
       if(ok){
           JOptionPane.showMessageDialog(this, "Walk cancelled");
           loadWalks();
       }
       else{
           JOptionPane.showMessageDialog(this,"Could not cancel this walk");
       }
    }//GEN-LAST:event_btnCancelWalkMouseClicked

    


